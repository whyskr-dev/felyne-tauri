// FCM (tauri-plugin-mobile-push) needs the google-services plugin, but the
// google-services.json is a CI secret. Only apply it when the file is present
// so local builds without Firebase still work.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

